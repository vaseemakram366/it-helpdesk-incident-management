#!/usr/bin/env python3
"""Generates 02_data.sql (realistic, reproducible sample data) for helpdesk_db.
Run:  python3 generate_data.py > 02_data.sql
Reference "now" is fixed (2026-11-15 10:00) so reports are reproducible."""
import random, sys, datetime as dt

random.seed(2026)
NOW = dt.datetime(2026, 11, 15, 10, 0, 0)
MIN = lambda m: dt.timedelta(minutes=m)


def q(v):
    if v is None: return "NULL"
    if isinstance(v, bool): return "1" if v else "0"
    if isinstance(v, (int, float)): return str(v)
    if isinstance(v, dt.datetime): return "'%s'" % v.strftime("%Y-%m-%d %H:%M:%S")
    if isinstance(v, dt.date): return "'%s'" % v.isoformat()
    return "'%s'" % str(v).replace("\\", "\\\\").replace("'", "''")


out, counts = ["-- AUTO-GENERATED by generate_data.py\nUSE helpdesk_db;\n"], {}


def ins(table, cols, rows):
    if not rows: return
    counts[table] = len(rows)
    out.append("INSERT INTO %s (%s) VALUES" % (table, ", ".join(cols)))
    out.append(",\n".join("  (" + ", ".join(q(v) for v in r) + ")" for r in rows) + ";\n")


# ---------- master data ----------
ins("department", ["dept_id", "dept_name", "location"],
    [(1, "IT Operations", "Block A"), (2, "Human Resources", "Block B"), (3, "Finance", "Block B"),
     (4, "Sales & Marketing", "Block C"), (5, "Engineering", "Block D"), (6, "Administration", "Block A")])
ins("user_role", ["role_id", "role_name"],
    [(1, "End User"), (2, "Helpdesk Agent"), (3, "IT Manager"), (4, "Administrator")])
ins("support_team", ["team_id", "team_name", "description"],
    [(1, "Desktop Support", "Laptops, desktops, printers"), (2, "Network Operations", "LAN, Wi-Fi, VPN"),
     (3, "Application Support", "Business apps, email, access"), (4, "Security Operations", "Malware, phishing, access abuse"),
     (5, "Infrastructure Tier-2", "Escalation team: servers, complex faults")])
ins("incident_status", ["status_id", "status_name", "is_final"],
    [(1, "New", 0), (2, "Assigned", 0), (3, "In Progress", 0), (4, "Escalated", 0), (5, "Resolved", 0), (6, "Closed", 1)])
ins("priority", ["priority_id", "priority_name", "rank_level"],
    [(1, "Critical", 1), (2, "High", 2), (3, "Medium", 3), (4, "Low", 4)])
SLA = {1: (15, 240), 2: (30, 480), 3: (120, 1440), 4: (480, 4320)}
ins("sla", ["sla_id", "sla_name", "priority_id", "response_minutes", "resolution_minutes"],
    [(p, "SLA-" + n, p, SLA[p][0], SLA[p][1]) for p, n in [(1, "Critical"), (2, "High"), (3, "Medium"), (4, "Low")]])

cat_team = {1: 1, 2: 3, 3: 2, 4: 3, 5: 4, 6: 1, 7: 1, 8: 2, 9: 2, 10: 3, 11: 4, 12: 3}
cats = [(1, "Hardware", None), (2, "Software", None), (3, "Network", None), (4, "Access Management", None),
        (5, "Security", None), (6, "Laptop Failure", 1), (7, "Printer Issue", 1), (8, "VPN Issue", 3),
        (9, "Wi-Fi Issue", 3), (10, "Password Reset", 4), (11, "Malware / Phishing", 5), (12, "Application Error", 2)]
ins("incident_category", ["category_id", "category_name", "parent_category_id", "default_team_id"],
    [(c, n, p, cat_team[c]) for c, n, p in cats])

firsts = ["Aarav", "Priya", "Rohan", "Sneha", "Vikram", "Ananya", "Karan", "Meera", "Arjun", "Diya",
          "Rahul", "Isha", "Nikhil", "Pooja", "Siddharth", "Kavya", "Manish", "Neha", "Amit", "Riya"]
lasts = ["Sharma", "Verma", "Gupta", "Singh", "Mehta", "Iyer", "Nair", "Khan", "Reddy", "Joshi"]
users = []
for i in range(1, 41):
    f, l = firsts[(i - 1) % 20], lasts[(i * 3) % 10]
    if i <= 10: dept, role = 1, 2
    elif i <= 12: dept, role = 1, 3
    elif i == 13: dept, role = 1, 4
    else: dept, role = random.randint(2, 6), 1
    users.append((i, f"{f} {l}", f"{f.lower()}.{l.lower()}{i}@corp.example",
                  f"98{random.randint(10000000, 99999999)}", dept, role, 1,
                  dt.datetime(2025, 1, 15, 9, 0, 0) + dt.timedelta(days=i * 3)))
ins("app_user", ["user_id", "full_name", "email", "phone", "dept_id", "role_id", "is_active", "created_at"], users)

techs = [(i, i, (i - 1) // 2 + 1, "L3" if i >= 9 else ("L1" if i % 2 else "L2"), 1) for i in range(1, 11)]
ins("technician", ["tech_id", "user_id", "team_id", "skill_level", "is_active"], techs)
team_techs = lambda t: [x[0] for x in techs if x[2] == t]

assets = []
models = {"Laptop": ["Dell Latitude 5440", "HP EliteBook 840", "Lenovo ThinkPad T14"],
          "Desktop": ["Dell OptiPlex 7010", "HP ProDesk 400"], "Printer": ["HP LaserJet Pro M404", "Canon iR2625"],
          "Server": ["Dell PowerEdge R750", "HPE ProLiant DL380"], "Router": ["Cisco ISR 4331"], "Switch": ["Cisco Catalyst 9200"]}
for a in range(1, 31):
    t = "Laptop" if a <= 12 else "Desktop" if a <= 18 else "Printer" if a <= 22 else "Server" if a <= 25 else ("Router" if a <= 27 else "Switch")
    owner = random.randint(14, 40) if t in ("Laptop", "Desktop") else None
    assets.append((a, f"AST-{a:04d}", t, random.choice(models[t]), owner,
                   dt.date(2022, 1, 1) + dt.timedelta(days=random.randint(0, 1100)),
                   random.choices(["Active", "Under Repair", "Retired"], [85, 10, 5])[0]))
ins("asset", ["asset_id", "asset_tag", "asset_type", "model", "assigned_user_id", "purchase_date", "asset_status"], assets)

services = [(1, "Corporate Email", 3, "High"), (2, "VPN Gateway", 2, "High"), (3, "ERP System", 3, "High"),
            (4, "HRMS Portal", 3, "Medium"), (5, "Intranet", 3, "Low"), (6, "Corporate Wi-Fi", 2, "High"),
            (7, "Payroll System", 3, "High"), (8, "File Server", 5, "Medium")]
ins("service", ["service_id", "service_name", "owner_team_id", "criticality"], services)

problems = [(1, "Printer driver crash after OS update", "Faulty universal print driver v3.2", "Known Error"),
            (2, "VPN drops under load", "Memory leak in VPN gateway firmware", "Under Investigation"),
            (3, "Wi-Fi disconnects on floor 3", "Access point firmware bug", "Under Investigation"),
            (4, "Laptop battery swelling (batch 2023-B)", "Defective battery batch from vendor", "Resolved"),
            (5, "ERP timeouts at month-end", "Unindexed report query on ERP DB", "Known Error")]
ins("problem", ["problem_id", "problem_title", "root_cause", "problem_status"], problems)

# ---------- incidents ----------
T = {6: ["Laptop not booting", "Laptop battery draining fast", "Laptop screen flickering"],
     7: ["Printer jammed on floor", "Printer offline", "Printer prints blank pages"],
     8: ["VPN disconnects frequently", "Cannot connect to VPN", "VPN very slow"],
     9: ["Wi-Fi keeps dropping", "No Wi-Fi in meeting room", "Wi-Fi authentication failed"],
     10: ["Forgot password", "Account locked", "Password expired - cannot login"],
     11: ["Suspicious phishing email received", "Antivirus detected malware", "Unknown pop-ups on desktop"],
     12: ["ERP report throws error", "HRMS portal timeout", "Intranet page not loading"]}
RESN = ["Fixed", "Workaround", "Replaced Hardware", "User Training", "Config Change"]
CMT = ["Quick resolution, thanks!", "Took longer than expected", "Agent was very helpful", "Issue fixed",
       "Had to follow up twice", "Excellent support", "Problem recurred later"]
ESC_REASON = ["SLA nearly breached", "Needs Tier-2 expertise", "Root cause in infrastructure", "Customer escalation"]
NOTE = {1: "Ticket created", 2: "Assigned to technician", 3: "Work started", 4: "Escalated to Tier-2", 5: "Resolved", 6: "Closed after confirmation"}

inc, hist, st_rows, res, fb, esc, ia, isv, ip = [], [], [], [], [], [], [], [], []
n_esc_res = 0
for i in range(1, 61):
    cat = random.choice([6, 7, 8, 9, 10, 11, 12])
    pr = random.choices([1, 2, 3, 4], [10, 25, 40, 25])[0]
    st = random.choices([1, 2, 3, 4, 5, 6], [4, 6, 8, 6, 26, 50])[0]
    rep = random.randint(14, 40)
    team = cat_team[cat]
    created = (NOW - MIN(random.randint(180, 7000))) if st <= 4 else (NOW - dt.timedelta(days=random.randint(9, 95), minutes=random.randint(0, 1400)))
    tech = assigned = resolved = closed = None
    esc_flag = (st == 4)
    if st in (5, 6) and pr <= 2 and n_esc_res < 4 and random.random() < 0.35:
        esc_flag, n_esc_res = True, n_esc_res + 1
    if st >= 2:
        tech = random.choice(team_techs(team))
        assigned = created + MIN(random.randint(3, 30) if pr == 1 else random.randint(5, 90))
    orig_team = team
    if esc_flag: team = 5
    if st >= 5:
        resolved = max(created + MIN(int(SLA[pr][1] * random.uniform(0.15, 1.6))), assigned + MIN(60))
    if st == 6: closed = resolved + dt.timedelta(hours=random.randint(4, 48))
    ticket = f"INC-2026-{i:05d}"
    inc.append((i, ticket, random.choice(T[cat]), f"Reported by user {rep}: {random.choice(T[cat])}. Please investigate.",
                rep, cat, pr, st, team, tech, created, assigned, resolved, closed))
    # history
    path = list(range(1, st + 1)) if st <= 3 else [1, 2, 3] + ([4] if esc_flag else []) + ([5] if st >= 5 else []) + ([6] if st == 6 else [])
    when = {1: created, 2: assigned, 3: assigned and assigned + MIN(10), 4: assigned and assigned + MIN(40), 5: resolved, 6: closed}
    prev = None
    for s in path:
        hist.append((i, prev, s, None if s <= 2 and s != 2 else (None if s == 2 else tech), tech if s >= 2 else None,
                     rep if s == 1 else tech, NOTE[s], when[s]))
        prev = s
    # SLA tracking
    rd, sd = created + MIN(SLA[pr][0]), created + MIN(SLA[pr][1])
    resp_b = (assigned > rd) if assigned else (NOW > rd)
    res_b = (resolved > sd) if resolved else (NOW > sd)
    st_rows.append((i, pr, rd, sd, assigned, int(resp_b), int(res_b)))
    if esc_flag:
        esc.append((i, orig_team, 5, random.choice(ESC_REASON), 1, assigned + MIN(40)))
    if st >= 5:
        res.append((i, tech, f"{random.choice(RESN)} applied for: {inc[-1][2]}", random.choice(RESN), resolved))
        if st == 6 and random.random() < 0.7:
            fb.append((i, random.choices([1, 2, 3, 4, 5], [3, 5, 12, 35, 45])[0], random.choice(CMT), closed + dt.timedelta(hours=random.randint(1, 30))))
    # assets / services / problems
    if cat == 6: ia.append((i, random.randint(1, 6)))
    if cat == 7: ia.append((i, random.randint(19, 22)))
    if cat in (8, 9): ia.append((i, random.randint(26, 30)))
    if cat == 11: ia.append((i, random.randint(13, 18)))
    sv = {8: [2], 9: [6], 10: [1], 11: [1], 12: random.sample([3, 4, 5, 7], 2)}.get(cat, [])
    for s in sv: isv.append((i, s))
    pmap = {7: 1, 8: 2, 9: 3}
    if cat in pmap and random.random() < 0.8: ip.append((i, pmap[cat]))
    if cat == 6 and ia and ia[-1][1] <= 2: ip.append((i, 4))
    if cat == 12 and 3 in sv and random.random() < 0.8: ip.append((i, 5))

ins("incident", ["incident_id", "ticket_no", "title", "description", "reporter_id", "category_id", "priority_id", "status_id",
                 "team_id", "assigned_tech_id", "created_at", "assigned_at", "resolved_at", "closed_at"], inc)
ins("incident_history", ["incident_id", "old_status_id", "new_status_id", "old_tech_id", "new_tech_id", "changed_by", "change_note", "changed_at"], hist)
ins("sla_tracking", ["incident_id", "sla_id", "response_due", "resolution_due", "responded_at", "response_breached", "resolution_breached"], st_rows)
ins("incident_asset", ["incident_id", "asset_id"], sorted(set(ia)))
ins("incident_service", ["incident_id", "service_id"], sorted(set(isv)))
ins("incident_problem", ["incident_id", "problem_id"], sorted(set(ip)))
ins("escalation", ["incident_id", "escalated_from_team", "escalated_to_team", "reason", "escalation_level", "escalated_at"], esc)
ins("resolution", ["incident_id", "resolved_by_tech_id", "resolution_text", "resolution_code", "resolved_at"], res)
ins("feedback", ["incident_id", "rating", "comments", "submitted_at"], fb)
ins("audit_log", ["table_name", "record_id", "action", "old_value", "new_value", "db_user", "event_time"],
    [("incident", i, "UPDATE", "status=2", "status=3", "agent@localhost", NOW - dt.timedelta(days=i)) for i in range(1, 9)])

print("\n".join(out))
total = sum(counts.values())
print("-- TOTAL ROWS: %d | %s" % (total, ", ".join(f"{k}={v}" for k, v in counts.items())))
sys.stderr.write("TOTAL ROWS: %d\n%s\n" % (total, counts))
